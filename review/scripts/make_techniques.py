"""Generate the per-study technique table and counts for report_techniques/.

Input:  review/data/top50.csv (from select_top50.py), review/data/extraction/coded_b0*.psv
Output: report_techniques/generated/numbers.tex, tab_techniques.tex

Each study is placed in one primary section of the techniques report by its coded RL family.
A study whose family code combines several families (e.g. "MARL+DQN") is listed under the first
matching entry of PRIMARY and its other families are counted as secondary techniques.
"""
import collections
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "review" / "data"
GEN = ROOT / "report_techniques" / "generated"

# family code -> (section label used in the table, macro suffix)
FAMILIES = {
    "TAB": ("Tabular Q", "Tab"),
    "DQN": ("DQN", "DQN"),
    "PG": ("Policy gradient", "PG"),
    "AC": ("Actor-critic", "AC"),
    "OFF": ("Offline RL", "Off"),
    "IL": ("Imitation", "IL"),
    "BANDIT": ("Bandit", "Bandit"),
    "MARL": ("Multi-agent", "MARL"),
    "MO": ("Multi-objective", "MO"),
}
# order in which a combined code picks its primary family (the more specific setting first)
PRIMARY = ["MARL", "MO", "OFF", "IL", "BANDIT", "AC", "PG", "DQN", "TAB"]
NONDESIGN = {"framework", "analysis"}

coded = {}
for f in sorted((DATA / "extraction").glob("coded_b0*.psv")):
    lines = f.read_text(encoding="utf-8").splitlines()
    head = lines[0].split("|")
    for line in lines[1:]:
        if line.strip():
            rec = dict(zip(head, line.split("|")))
            coded[rec["id"]] = rec

top = list(csv.DictReader(open(DATA / "top50.csv", encoding="utf-8")))


def tex(s):
    s = s.replace("\\", "/").replace("&", "\\&").replace("%", "\\%").replace("_", "\\_").replace("#", "\\#")
    return s.replace(">", "$>$").replace("<", "$<$")


def primary(fam, contrib):
    codes = [c for c in re.split(r"[+;]", fam) if c in FAMILIES]
    if contrib in NONDESIGN or not fam:
        return "Tooling", codes
    if not codes:
        return "Deep RL (n.s.)", codes
    for p in PRIMARY:
        if p in codes:
            return FAMILIES[p][0], codes
    return "Deep RL (n.s.)", codes


ACTION = {"cwnd": "cwnd", "rate": "rate", "bitrate": "bitrate", "param": "parameter", "select": "algorithm choice",
          "aqm": "drop/mark", "ecn": "ECN threshold", "split": "traffic split"}
REWARD = {"thr": "throughput", "delay": "delay", "loss": "loss", "util": "utility", "power": "power",
          "qoe": "QoE", "fct": "FCT", "fair": "fairness", "other": "other"}

rows, any_count, prim_count = [], collections.Counter(), collections.Counter()
for t in top:
    c = coded[t["id"]]
    sec, codes = primary(c["family"], t["contrib"])
    prim_count[sec] += 1
    for code in set(codes):
        any_count[code] += 1
    act = "; ".join(ACTION.get(a, a) for a in c["action"].split(";") if a) or "--"
    if t["contrib"] in NONDESIGN:
        act, rew = "--", "--"
    rew = ", ".join(REWARD.get(r, r) for r in c["reward"].split(",") if r and r != "NA") or "--"
    rew = rew.replace("NR", "n.r.")
    aspace = {"C": "cont.", "D": "disc."}.get(c["aspace"], "")
    if aspace and act != "--":
        act = f"{act} ({aspace})"
    rows.append(f"{t['rank']} & {tex(t['name'])}~\\cite{{{t['bibkey']}}} & {sec} & {tex(c['algo'])} & {tex(act)} & {tex(rew)} \\\\")

GEN.mkdir(parents=True, exist_ok=True)
(GEN / "tab_techniques.tex").write_text(
    "% generated by review/scripts/make_techniques.py (do not edit by hand)\n" + "\n".join(rows) + "\n", encoding="utf-8")

macros = {"N": len(top), "Design": sum(t["contrib"] not in NONDESIGN for t in top),
          "Tooling": prim_count["Tooling"], "Unspecified": prim_count["Deep RL (n.s.)"]}
for code, (label, suffix) in FAMILIES.items():
    macros["Any" + suffix] = any_count[code]
    macros["Prim" + suffix] = prim_count[label]
macros["Deep"] = sum(1 for t in top if t["contrib"] not in NONDESIGN and coded[t["id"]]["family"] not in ("TAB", "BANDIT"))
macros["Hybrid"] = sum(1 for t in top if t["contrib"] not in NONDESIGN and coded[t["id"]]["hybrid"] == "Y")
out = ["% generated by review/scripts/make_techniques.py (do not edit by hand)"]
out += [f"\\newcommand{{\\t{k}}}{{{v}\\xspace}}" for k, v in sorted(macros.items())]
# bare values (no \xspace) for use inside pgfplots coordinates
out += [f"\\newcommand{{\\tv{k}}}{{{v}}}" for k, v in sorted(macros.items())]
(GEN / "numbers.tex").write_text("\n".join(out) + "\n", encoding="utf-8")

for k, v in sorted(macros.items()):
    print(k, v)
