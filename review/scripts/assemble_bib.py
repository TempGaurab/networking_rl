"""Assemble survey/references.bib from the background, manual and corpus files.

Entries are kept in that order of precedence; a later entry is dropped when its
key or DOI already appeared. Mojibake from cp1252-decoded UTF-8 is repaired and
HTML entities are unescaped so that BibTeX sees plain LaTeX.
"""
import html
import json
import re

import pandas as pd

from common import DATA, ROOT

SURVEY = ROOT.parent / "survey"
FILES = ["references_background.bib", "references_manual.bib", "references_corpus.bib"]
MOJIBAKE = {"â€“": "--", "â€”": "---", "â€™": "'", "â€œ": "``", "â€\u009d": "''", "â€": "''", "Ã©": "é", "Ã¶": "ö",
            "Ã¼": "ü", "Ã¡": "á", "Ã³": "ó", "Ã±": "ñ"}


def entries(text):
    """Split a .bib file into (key, entry_text) pairs by brace matching."""
    out, i = [], 0
    while True:
        m = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,").search(text, i)
        if not m:
            return out
        depth, j = 0, m.end() - 1
        j = text.index("{", m.start())
        for k in range(j, len(text)):
            if text[k] == "{":
                depth += 1
            elif text[k] == "}":
                depth -= 1
                if depth == 0:
                    break
        out.append((m.group(2), text[m.start():k + 1]))
        i = k + 1


DROP_FIELDS = ("series", "collection", "ISSN")  # Crossref extras that IEEEtranN prints as noise
# titles that the publisher registered in all capitals
TITLE_OVERRIDE = {
    "lakshmi2023comparison": "Comparison and Implementation of Protocols to Compensate for Congestion in Networks "
                             "with Reinforcement Learning",
}


def clean(e):
    for bad, good in MOJIBAKE.items():
        e = e.replace(bad, good)
    for f in DROP_FIELDS:
        e = re.sub(r",\s*" + f + r"\s*=\s*\{[^{}]*\}", "", e, flags=re.I)
    e = e.replace("\u2019", "'").replace("\u2018", "`").replace("\u2032", "'").replace("\u00a0", " ")
    e = e.replace("\u201c", "``").replace("\u201d", "''")
    e = protect_title(e)
    e = html.unescape(e).replace(" & ", r" \& ").replace("–", "--").replace("—", "---")
    e = re.sub(r"(?<!\\)&(?!\s)", r"\\&", e)
    return e


def ordered_entries():
    """Study keys first (so that every key cited by the generated tables survives), then the
    background and manual files, then the remaining corpus entries."""
    st = pd.read_csv(DATA / "studies_enriched.csv", dtype=str, keep_default_na=False)
    study_keys = set(st.bibkey) | {k for x in st.linked_keys for k in x.split(";") if k}
    corpus = entries((SURVEY / FILES[2]).read_text(encoding="utf-8"))
    out = [(FILES[2], k, e) for k, e in corpus if k in study_keys]
    for fn in FILES[:2]:
        out += [(fn, k, e) for k, e in entries((SURVEY / fn).read_text(encoding="utf-8"))]
    return out + [(FILES[2], k, e) for k, e in corpus if k not in study_keys]


def protect_title(e):
    """Wrap the title in an extra brace pair so that IEEEtranN keeps its case (acronyms such as
    TCP, QUIC, 5G and names such as Pantheon would otherwise be lower-cased)."""
    m = re.search(r"\btitle\s*=\s*\{", e, flags=re.I)
    if not m:
        return e
    start, depth = m.end() - 1, 0
    for k in range(start, len(e)):
        if e[k] == "{":
            depth += 1
        elif e[k] == "}":
            depth -= 1
            if depth == 0:
                break
    inner = e[start + 1:k]
    if inner.startswith("{") and inner.endswith("}"):
        return e
    return e[:start + 1] + "{" + inner + "}" + e[k:]


def main():
    seen_keys, seen_dois, kept, dropped = set(), {}, [], []
    for fn, key, e in ordered_entries():
        if True:
            doi = re.search(r"\bdoi\s*=\s*\{([^}]+)\}", e, flags=re.I)
            doi = doi.group(1).lower().strip() if doi else None
            if key in seen_keys or (doi and doi in seen_dois):
                dropped.append((fn, key, seen_dois.get(doi, key)))
                continue
            seen_keys.add(key)
            if doi:
                seen_dois[doi] = key
            if key in TITLE_OVERRIDE:
                e = re.sub(r"\btitle\s*=\s*\{.*?\}(?=,\s*\w+\s*=)", "title={" + TITLE_OVERRIDE[key] + "}", e,
                           count=1, flags=re.S)
            kept.append(clean(e))
    (SURVEY / "references.bib").write_text("% generated by review/scripts/assemble_bib.py -- do not edit\n\n"
                                           + "\n\n".join(kept) + "\n", encoding="utf-8")
    aliases = {key: other for _, key, other in dropped if key != other}
    (DATA / "bib_aliases.json").write_text(json.dumps(aliases, indent=1) + "\n")
    print(f"{len(kept)} entries written; dropped duplicates:")
    for fn, key, other in dropped:
        print(f"  {fn}: {key} (same as {other})")


if __name__ == "__main__":
    main()
